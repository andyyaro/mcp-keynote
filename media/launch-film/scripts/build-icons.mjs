#!/usr/bin/env node
// Writes the HIG Native line glyphs used by the scenes into index.html as an inline SVG sprite
// (between <!-- HF:ICONS --> and <!-- /HF:ICONS -->). Scenes draw them with
// <svg class="ic"><use href="#ic-NAME"/></svg>; strokes inherit currentColor (1.8, round caps/joins).
// Source data: scripts/vendor/hig-icons.js (copied unchanged from the HIG Native design system).
// Usage: node scripts/build-icons.mjs [projectDir]
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { ICONS } from "./vendor/hig-icons.js";

const dir = resolve(process.argv[2] || ".");
const USED = [
  "person.crop.circle", "doc", "list.bullet", "checkmark.circle", "square.3.layers.3d.top.filled", "square.grid.2x2",
  "document.on.document", "photo", "arrow.uturn.backward", "lock", "play.fill", "square.and.arrow.up",
  "checkmark.circle.fill", "xmark.circle.fill", "flag", "gearshape", "arrow.uturn.forward", "globe", "chevron.right",
  "text.alignleft", "checkmark",
];

const SW = 1.8;
const attr = (k, v) => `${k === "sw" ? "" : `${k}="${v}"`}`;
function shape([tag, a]) {
  const out = [];
  let fill = "none", stroke = "currentColor", width = SW;
  for (const [k, v] of Object.entries(a)) {
    if (k === "fill") { fill = "currentColor"; stroke = "none"; continue; }
    if (k === "knock") { stroke = "var(--knock, #fff)"; continue; }
    if (k === "sw") { width = SW * v; continue; }
    out.push(attr(k, v));
  }
  if (a.fill) return `<${tag} ${out.join(" ")} fill="${fill}" stroke="${stroke}"/>`;
  return `<${tag} ${out.join(" ")} fill="none" stroke="${stroke}" stroke-width="${width}"/>`;
}
const symbols = USED.map((name) => {
  const s = ICONS[name];
  if (!s) throw new Error(`icon ${name} not in hig-icons.js`);
  return `        <symbol id="ic-${name.replace(/\./g, "-")}" viewBox="0 0 24 24" stroke-linecap="round" stroke-linejoin="round">${s.map(shape).join("")}</symbol>`;
});
const block = `<!-- HF:ICONS (generated by scripts/build-icons.mjs, do not hand-edit) -->
      <svg id="ic-sprite" width="0" height="0" aria-hidden="true" style="position:absolute;width:0;height:0;overflow:hidden">
${symbols.join("\n")}
      </svg>
      <!-- /HF:ICONS -->`;
const file = join(dir, "index.html");
let html = readFileSync(file, "utf8");
if (!/<!-- HF:ICONS[\s\S]*?<!-- \/HF:ICONS -->/.test(html)) throw new Error("HF:ICONS markers not found in index.html");
html = html.replace(/<!-- HF:ICONS[\s\S]*?<!-- \/HF:ICONS -->/, block);
writeFileSync(file, html);
console.log(`icons: ${USED.length} glyphs written to the sprite`);
